function localeKey() {
  const raw = String(vscode.env.language || 'en').toLowerCase();
  if (raw === 'ru' || raw.startsWith('ru-')) return 'ru';
  if (raw === 'zh-cn' || raw === 'zh-hans' || raw.startsWith('zh-cn') || raw.startsWith('zh-hans')) return 'zh-cn';
  return 'en';
}

function s(key, vars = {}) {
  const dict = STRINGS[localeKey()] || STRINGS.en;
  let value = dict[key] ?? STRINGS.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

module.exports = { STRINGS, localeKey, s };
